def _skill(name, warmup, cd, rng, aoe, info, actions,
           hp_type=0, ban_stand=1):
    # Avatar.attackAimList treats pl[4] as EXTRA targets: 0 = one target,
    # 1 = two targets, ... 199 = whole line, >=200 = positional AoE.
    # Callers pass the desired target count, so convert it here.
    aoe_field = aoe - 1 if 0 < aoe < 200 else aoe
    return {
        "name": name,
        "pl": [warmup, cd, rng, hp_type, aoe_field, ban_stand],
        "skill": actions,
        # scale the first (damage/heal) action with skill level; index 2
        # would be out of range for one-action kits.
        "skillUp": [0, 0.1],
        "info": info,
    }


def _raw_skill(name, pl, actions, info, skill_up=None):
    """Skill with an explicit pl array (whole-line / field-wide kits)."""
    return {
        "name": name,
        "pl": list(pl),
        "skill": actions,
        "skillUp": list(skill_up) if skill_up else [0, 0],
        "info": info,
    }


E = {  # common effect ids (see cfg.effect)
    "slash": "E_014", "arrow": "E_008", "magic": "E_009",
    "holy": "E_010", "stun": "E_005", "shield": "E_001",
}


def _dtype(fx):
    """1=physical, 2=magic, 3=true.  The action array's 3rd slot is the
    damage type, NOT a target count (targets come from pl[4])."""
    return 2 if fx in (E["magic"], E["holy"]) else 1


def D(c, n=1, fx=E["slash"]):
    return ["damage", c, _dtype(fx), fx]


def AOE(c, targets, fx=E["magic"]):
    # ``targets`` only documents intent; the real count lives in pl[4].
    return ["damage", c, _dtype(fx), fx]

